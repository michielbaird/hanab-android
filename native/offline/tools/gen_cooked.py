"""Writes src/rng_cooked.rs from Go's math/rand source (rng.go): the table its generator is seeded from."""
import re
import sys

src = open(sys.argv[1] + '/rng.go', encoding='utf-8').read()
body = src[src.index('rngCooked [rngLen]int64'):]
body = body[body.index('{') + 1:]
body = body[:body.index('}')]
values = [int(x) for x in re.findall(r'-?\d+', body)]
assert len(values) == 607, len(values)
lines = ['// The table Go\'s math/rand seeds its generator from (rngCooked in src/math/rand/rng.go).',
         '// Copyright 2009 The Go Authors. All rights reserved. Use of this source code is governed by a BSD-style',
         '// license: https://go.dev/LICENSE',
         '// Generated by gen_cooked.py; do not edit.',
         'pub const RNG_COOKED: [i64; 607] = [']
for i in range(0, 607, 4):
    lines.append('    ' + ', '.join(f'{v}' for v in values[i:i + 4]) + ',')
lines.append('];')
open('src/rng_cooked.rs', 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('wrote', len(values), 'values')
